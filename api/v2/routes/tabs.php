$app->get('/tabs', function ($request, $response, $args) {
	$Londerland = ($request->getAttribute('Londerland')) ?? new Londerland();
	if ($Londerland->qualifyRequest(1, true)) {
		$GLOBALS['api']['response']['data'] = $Londerland->getAllTabs();
	}
